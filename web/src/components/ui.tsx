import { useState, type ReactNode } from 'react'
import { feedKey, timeAgo, type FeedItem } from '../api'

export function Card({ children, className = '' }: { children: ReactNode; className?: string }) {
  return <section className={`rounded-2xl border border-line bg-card p-4 shadow-[0_1px_0_#e3dac8] ${className}`}>{children}</section>
}

export function SimBadge() {
  return (
    <span title="Generated by the seed script, not measured" className="rounded-full border border-amber/50 bg-amber/10 px-2 py-0.5 text-[11px] font-semibold uppercase tracking-wide text-amber">
      Simulated
    </span>
  )
}

export function LiveBadge() {
  return (
    <span className="inline-flex items-center gap-1 rounded-full bg-leaf-soft px-2 py-0.5 text-[11px] font-semibold uppercase tracking-wide text-leaf">
      <span className="h-1.5 w-1.5 animate-pulse rounded-full bg-leaf" /> Live
    </span>
  )
}

export function Stat({ label, value, sub, badge }: { label: string; value: ReactNode; sub?: ReactNode; badge?: ReactNode }) {
  return (
    <Card>
      <div className="flex items-center justify-between gap-2 text-sm text-muted">{label}{badge}</div>
      <div className="mt-1 font-display text-3xl font-bold">{value}</div>
      {sub && <div className="mt-1 text-sm text-muted">{sub}</div>}
    </Card>
  )
}

// Inline icons (stroke, 24px grid) so they render the same on every device, unlike emoji.
const ICON_PATHS: Record<string, { d: string[]; color: string }> = {
  report: { d: ['M3 11v2a1 1 0 0 0 1 1h2l5 4V6L6 10H4a1 1 0 0 0-1 1z', 'M15 9a3 3 0 0 1 0 6', 'M18 6a7 7 0 0 1 0 12'], color: 'text-alert' },
  collection: { d: ['M7 19H4.8a1.8 1.8 0 0 1-1.6-2.7L7 10', 'M11 19h8.2a1.8 1.8 0 0 0 1.6-2.7L19 13', 'M14 16l-3 3 3 3', 'M8.3 13.6L7 10l-3.6 1.3', 'M9.3 5.3L11.4 2a1.8 1.8 0 0 1 3 0l3.6 6', 'M14.5 7.9l3.5.1.7-3.7'], color: 'text-leaf' },
  pickup: { d: ['M21 8l-9-5-9 5 9 5 9-5z', 'M3 8v8l9 5 9-5V8', 'M12 13v8'], color: 'text-kraft' },
}

function FeedIcon({ type }: { type: string }) {
  const icon = ICON_PATHS[type] ?? ICON_PATHS.report
  return (
    <svg viewBox="0 0 24 24" className={`mt-0.5 h-5 w-5 shrink-0 ${icon.color}`} fill="none" stroke="currentColor" strokeWidth="1.8" strokeLinecap="round" strokeLinejoin="round" aria-hidden>
      {icon.d.map((d) => <path key={d} d={d} />)}
    </svg>
  )
}

/** Items that weren't in the previous render flash in, so a voice report visibly "lands" on screen. */
export function Feed({ items }: { items: FeedItem[] }) {
  const [prevItems, setPrevItems] = useState(items)
  const [fresh, setFresh] = useState<Set<string>>(new Set())
  if (items !== prevItems) {  // derive "new since last poll" during render (no effect, no ref)
    const old = new Set(prevItems.map(feedKey))
    setFresh(prevItems.length ? new Set(items.map(feedKey).filter((k) => !old.has(k))) : new Set())
    setPrevItems(items)
  }
  if (!items.length) return <p className="text-sm text-muted">Nothing yet — talk to the agent on the Collector tab.</p>
  return (
    <ul className="divide-y divide-line">
      {items.map((i) => (
        <li key={feedKey(i)} className={`flex gap-3 px-1 py-2.5 ${fresh.has(feedKey(i)) ? 'flash-in' : ''}`}>
          <FeedIcon type={i.type} />
          <div className="min-w-0 flex-1">
            <div className="text-sm"><b>{i.location}</b> · {i.text}</div>
            <div className="mt-0.5 flex flex-wrap items-center gap-2 text-xs text-muted">
              <span>{i.who} via {i.channel}</span><span>{timeAgo(i.ts)}</span>{i.simulated && <SimBadge />}
            </div>
          </div>
        </li>
      ))}
    </ul>
  )
}
