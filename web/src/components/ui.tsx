import type { ReactNode } from 'react'
import { timeAgo, type FeedItem } from '../api'

export function Card({ children, className = '' }: { children: ReactNode; className?: string }) {
  return <section className={`rounded-2xl border border-line bg-card p-4 shadow-[0_1px_0_#e3dac8] ${className}`}>{children}</section>
}

export function SimBadge() {
  return (
    <span title="Generated by the seed script, not measured" className="rounded-full border border-amber/50 bg-amber/10 px-2 py-0.5 text-[11px] font-semibold uppercase tracking-wide text-amber">
      Simulated
    </span>
  )
}

export function LiveBadge() {
  return (
    <span className="inline-flex items-center gap-1 rounded-full bg-leaf-soft px-2 py-0.5 text-[11px] font-semibold uppercase tracking-wide text-leaf">
      <span className="h-1.5 w-1.5 animate-pulse rounded-full bg-leaf" /> Live
    </span>
  )
}

export function Stat({ label, value, sub, badge }: { label: string; value: ReactNode; sub?: ReactNode; badge?: ReactNode }) {
  return (
    <Card>
      <div className="flex items-center justify-between gap-2 text-sm text-muted">{label}{badge}</div>
      <div className="mt-1 font-display text-3xl font-bold">{value}</div>
      {sub && <div className="mt-1 text-sm text-muted">{sub}</div>}
    </Card>
  )
}

const ICON: Record<string, string> = { report: '📣', collection: '♻️', pickup: '📦' }

export function Feed({ items }: { items: FeedItem[] }) {
  if (!items.length) return <p className="text-sm text-muted">Nothing yet — talk to the agent on the Collector tab.</p>
  return (
    <ul className="divide-y divide-line">
      {items.map((i, n) => (
        <li key={n} className="flex gap-3 py-2.5">
          <span className="text-lg leading-6">{ICON[i.type]}</span>
          <div className="min-w-0 flex-1">
            <div className="text-sm"><b>{i.location}</b> · {i.text}</div>
            <div className="mt-0.5 flex flex-wrap items-center gap-2 text-xs text-muted">
              <span>{i.who} via {i.channel}</span><span>{timeAgo(i.ts)}</span>{i.simulated && <SimBadge />}
            </div>
          </div>
        </li>
      ))}
    </ul>
  )
}
